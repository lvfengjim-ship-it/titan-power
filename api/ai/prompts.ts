// lang: 'zh'（默认）输出中文报告；'en' 输出全英文报告
export type ReportLang = "zh" | "en";

/** 请求体中的 lang 字段归一化：非法值一律按 'zh' */
export function normalizeReportLang(value: unknown): ReportLang {
  return value === "en" ? "en" : "zh";
}

